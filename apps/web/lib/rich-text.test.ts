import assert from "node:assert/strict";
import test from "node:test";
import { processRichTextContent } from "./rich-text.js";

test("renders headings with inline emphasis", () => {
	const html = processRichTextContent("## Um título *importante*");

	assert.equal(html, "<h2>Um título <em>importante</em></h2>");
});

test("renders multi-paragraph blockquotes and italic attribution", () => {
	const markdown = [
		"> “Nós lutamos e exigimos respeito e a naturalização de nossas existências.”",
		">",
		"> *(Alan Costa)*",
	].join("\n");

	const html = processRichTextContent(markdown);

	assert.equal(
		html,
		"<blockquote><p>“Nós lutamos e exigimos respeito e a naturalização de nossas existências.”</p><p><em>(Alan Costa)</em></p></blockquote>",
	);
});

test("renders headings and blockquotes when the editor escapes their markers", () => {
	const markdown = [
		"\\# teste",
		"",
		"\\> asdasdasdadsdasdsd",
	].join("\n");

	assert.equal(
		processRichTextContent(markdown),
		"<h1>teste</h1><blockquote><p>asdasdasdadsdasdsd</p></blockquote>",
	);
});

test("renders images, lists and external links without escaping markdown", () => {
	const markdown = [
		"![Ilustração](https://example.com/image.png)",
		"",
		"- **Primeiro** item",
		"- [Saiba mais](https://example.com)",
	].join("\n");

	const html = processRichTextContent(markdown);

	assert.match(
		html,
		/<img src="https:\/\/example.com\/image.png" alt="Ilustração" loading="lazy" \/>/,
	);
	assert.match(html, /<ul><li><strong>Primeiro<\/strong> item<\/li>/);
	assert.match(
		html,
		/<a href="https:\/\/example.com" rel="noreferrer" target="_blank">Saiba mais<\/a>/,
	);
});

test("renders a YouTube directive as a responsive iframe", () => {
	const html = processRichTextContent(
		'::video{url="https://www.youtube.com/watch?v=-8kX9kLb8K0"}',
	);

	assert.match(html, /<figure class="media my-6">/);
	assert.match(
		html,
		/src="https:\/\/www.youtube-nocookie.com\/embed\/-8kX9kLb8K0"/,
	);
	assert.doesNotMatch(html, /__KIANDA_VIDEO_EMBED_/);
});

test("preserves supported HTML generated by the rich text editor", () => {
	const html = processRichTextContent(
		[
			"<h2>Título <u>sublinhado</u></h2>",
			"",
			"<blockquote><p>Uma citação.</p><p><em>Autoria</em></p></blockquote>",
			"",
			'<img src="https://example.com/photo.png" alt="Foto do artigo" />',
		].join("\n"),
	);

	assert.match(html, /<h2>Título <u>sublinhado<\/u><\/h2>/);
	assert.match(
		html,
		/<blockquote><p>Uma citação.<\/p><p><em>Autoria<\/em><\/p><\/blockquote>/,
	);
	assert.match(
		html,
		/<img src="https:\/\/example.com\/photo.png" alt="Foto do artigo" loading="lazy" \/>/,
	);
});

test("keeps HTML headings and blockquotes intact when they contain empty lines", () => {
	const html = processRichTextContent(
		[
			'<h3 data-lexical-heading="true">Um título <u>sublinhado</u></h3>',
			"",
			"<blockquote>",
			"  <p>Uma citação em dois parágrafos.</p>",
			"",
			"  <p><em>Autoria</em></p>",
			"</blockquote>",
		].join("\n"),
	);

	assert.equal(
		html,
		"<h3>Um título <u>sublinhado</u></h3><blockquote><p>Uma citação em dois parágrafos.</p><p><em>Autoria</em></p></blockquote>",
	);
});

test("renders headings, quotes and lists saved with CRLF line breaks", () => {
	const markdown = [
		"# teste",
		"",
		"> asdasdasdadsdasdsd",
		"",
		"- primeiro item",
		"- segundo item",
	].join("\r\n");

	assert.equal(
		processRichTextContent(markdown),
		"<h1>teste</h1><blockquote><p>asdasdasdadsdasdsd</p></blockquote><ul><li>primeiro item</li><li>segundo item</li></ul>",
	);
});

test("renders multi-paragraph blockquotes saved with CRLF line breaks", () => {
	const markdown = ["> linha 1", ">", "> linha 2"].join("\r\n");

	assert.equal(
		processRichTextContent(markdown),
		"<blockquote><p>linha 1</p><p>linha 2</p></blockquote>",
	);
});
